Проверять продукт нужно, чтобы до выхода к пользователям понять, решает ли он их задачу и где могут возникнуть риски. Если человек не может войти в свой аккаунт с верным паролем, он не сможет пользоваться сервисом.

Чтобы заметить проблему, тестировщик сначала выясняет, как продукт должен вести себя. Ответ бывает в требовании, макете или договорённости команды. Затем он выполняет конкретные действия и смотрит, что произошло на самом деле.

Такая работа называется тестированием. Она помогает найти дефекты, проверить важные сценарии и дать команде информацию для решения. Тестирование не может доказать, что ошибок нет совсем.
