В примере со входом мы ожидали личный кабинет, а увидели сообщение об ошибке. Так тестировщик сравнивает два результата проверки.

**Ожидаемый результат** показывает, что должно произойти при выполнении условий по требованию или правилу. **Фактический результат** показывает, что произошло после конкретных действий. Например, пароль может содержать до 30 символов. Ты вводишь 50 символов и отправляешь форму. Ожидаешь предупреждение, а форма создаёт аккаунт.

Если правило неясно, не спеши называть поведение дефектом. Сначала уточни его у команды. Понятные условия, шаги и оба результата помогут другому человеку воспроизвести ситуацию и принять решение.
