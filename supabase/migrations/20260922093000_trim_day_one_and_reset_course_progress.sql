QA-инженер не только проверяет готовый продукт. Он читает задачи до разработки, уточняет непонятные правила, продумывает сценарии, описывает проблемы и перепроверяет исправления.

Допустим, в задаче написано, что пользователь может восстановить пароль, но срок действия ссылки не указан. QA задаёт вопрос заранее. Команда договаривается о правиле, а затем проверяет готовую функцию. Так проблема не дойдёт до пользователя.

Поэтому QA шире отдельного теста. Он помогает команде работать с качеством, а тестирование даёт сведения о конкретном поведении продукта. Разработчик, дизайнер и менеджер используют эту информацию, чтобы решить, что менять и когда выпускать продукт.
