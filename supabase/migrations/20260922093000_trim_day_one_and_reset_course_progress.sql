Тестировщик сначала выясняет, как продукт должен вести себя. Ответ бывает в требовании, макете или договорённости команды. Затем он выполняет конкретные действия и сравнивает ожидание с тем, что произошло на самом деле.

Тестирование помогает найти дефекты, проверить важные сценарии и понять риски. Оно не может доказать, что ошибок нет совсем. Хороший тестировщик сообщает команде, что проверял, что ожидал и что увидел.
