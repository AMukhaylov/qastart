Представь магазин, где для заказа обещана скидка 10%, а на экране показана полная цена. Мы видим неправильное поведение: ожидали скидку, но её нет. Причина может быть в расчёте, настройке акции или требовании.

Полезно различать ошибку человека, дефект и его проявление. Ошибочное решение или строка кода может привести к дефекту. Неправильная сумма, которую видит пользователь, становится его проявлением.

Задача тестировщика состоит в том, чтобы зафиксировать наблюдение. Какие товары были в корзине, какую скидку ожидали, что показал экран и можно ли повторить ситуацию. Дальше команда ищет причину.
