В каждой проверке есть два важных понятия. **Ожидаемый результат** показывает, что должно произойти по правилу. **Фактический результат** показывает, что произошло во время проверки.

Например, в требовании указано, что пароль может содержать до 30 символов. Ты вводишь 50 символов и отправляешь форму. Ожидаешь предупреждение, а форма создаёт аккаунт. Есть правило и есть наблюдение, их можно сравнить.

Если требование неясно, не спеши называть поведение дефектом. Сначала уточни правило. Понятные условия, шаги и оба результата помогут другому человеку воспроизвести ситуацию и принять решение.
