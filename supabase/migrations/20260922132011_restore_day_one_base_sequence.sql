Тестировщик начинает с вопроса: **как продукт должен себя вести?** Ответ может быть в требовании, макете, договорённости команды или в понятной пользователю логике. Затем он выполняет конкретные действия и наблюдает результат. Например, отправляет перевод при обычном соединении и при временном обрыве сети. Так проверка связывает ожидание с тем, что действительно произошло.

Цель тестирования не только найти дефект. Проверки помогают понять, выполняет ли продукт важные ожидания, где могут возникнуть риски и какую информацию нужно дать команде для решения. Иногда результат проверки — найденная ошибка, а иногда подтверждение, что выбранный сценарий работает. Но даже сотни удачных проверок не доказывают, что ошибок нигде нет: невозможно перебрать абсолютно все устройства, данные и действия пользователей.

Информация от тестирования полезна всей команде. Разработчик получает понятный случай для исследования, дизайнер видит неудобный шаг, менеджер понимает риск для запуска. Именно поэтому хороший тестировщик сообщает не просто «сломалось», а что проверял, какой результат ожидал, что увидел и чем это важно для пользователя.
